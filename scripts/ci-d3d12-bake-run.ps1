# Bake the shader variants one model needs, and check the GPU output against the CPU's.
#
# Runs on a GitHub Windows runner against the software D3D12 adapter (WARP), with the *desktop* build of
# xllama's pinned llama.cpp + the vendored whole-graph backend (see scripts/d3d12-full-inject.py).
#   * every pipeline the graphs request is compiled by DXC and saved as DXIL in $CacheDir (named by a
#     hash of source + compiler args, exactly the key the console build looks up);
#   * GGML_D3D12_FAKE_VENDOR=1002 makes the adapter request the pipelines an AMD UMA GPU (the Xbox)
#     requests;
#   * GGML_D3D12_MANIFEST records "<file>\t<pipeline key>" per pipeline, for coverage reports;
#   * -Check generates greedily on the CPU and on the GPU and compares the text.
param(
    [Parameter(Mandatory)] [string] $Name,
    [Parameter(Mandatory)] [string] $Url,
    [string] $Pp = "4,16,64,256",   # prompt sizes for llama-bench (columns: <16 and >=16 pick different kernels)
    [int]    $N = 8,                # tokens generated by llama-bench
    [string] $Kind = "llm",         # llm | embed
    [switch] $Check,
    [switch] $Ppl,                  # also compare perplexity CPU vs GPU (needs llama-perplexity)
    [int]    $PplCtx = 128,
    [int]    $PplChunks = 3,
    [switch] $Fast,                 # only the default-path bench (huge models: each run takes ~15 min on WARP)
    [int]    $CheckTokens = 16,
    [int]    $TimeoutMin = 40,
    [string] $Only = "all",          # all | fa1 | fa0 | kvq8 : which llama-bench configuration(s) to run
    [string] $Mode = "bake",         # bake: compile + save shaders | verify: cache-only build, fail on any missing shader
    [string] $CacheDir = ""          # verify: folder with the merged baked cache
)
$ErrorActionPreference = "Continue"
$ws = $env:GITHUB_WORKSPACE
$tools = Join-Path $ws "tools"
$cache = Join-Path $ws "cache"
$logs = Join-Path $ws "logs"
New-Item -ItemType Directory -Force $cache, $logs | Out-Null

$env:GGML_D3D12_WARP = "1"
$env:GGML_D3D12_FAKE_VENDOR = "1002"
if ($Mode -eq "verify") {
    $env:GGML_D3D12_CACHE_DIR = $CacheDir   # cache-only build: nothing can be compiled, nothing is written
} else {
    $env:GGML_D3D12_CACHE_DIR = $cache
    $env:GGML_D3D12_MANIFEST = Join-Path $ws "manifest.txt"
}
$script:failed = $false

$model = Join-Path $ws "model.gguf"
Write-Host "== download $Name"
for ($i = 1; $i -le 3 -and -not (Test-Path $model); $i++) {
    curl.exe -L --fail --retry 3 -s -o $model $Url
    if ($LASTEXITCODE -ne 0) { Remove-Item $model -ErrorAction SilentlyContinue; Start-Sleep 5 }
}
if (-not (Test-Path $model)) { "download failed: $Url" | Out-File "$logs/FAILED.txt"; exit 1 }
"{0} {1} MB" -f $Name, [int]((Get-Item $model).Length / 1MB) | Tee-Object "$logs/model.txt"

function Invoke-Timed($exe, $argList, $tag) {
    $o = Join-Path $logs "$tag.out.txt"; $e = Join-Path $logs "$tag.err.txt"
    Write-Host "== $tag : $exe $argList"
    $sw = [Diagnostics.Stopwatch]::StartNew()
    $p = Start-Process -FilePath (Join-Path $tools $exe) -ArgumentList $argList -NoNewWindow -PassThru `
         -RedirectStandardOutput $o -RedirectStandardError $e
    if (-not $p.WaitForExit($TimeoutMin * 60000)) { $p.Kill(); "TIMEOUT $tag" | Out-File -Append "$logs/timeouts.txt" }
    "{0}: exit={1} {2:n0}s" -f $tag, $p.ExitCode, $sw.Elapsed.TotalSeconds | Out-File -Append "$logs/summary.txt"
    if ($p.ExitCode -ne 0) { $script:failed = $true }
    return $p.ExitCode
}

if ($Kind -eq "embed") {
    Invoke-Timed "llama-embedding.exe" "-m `"$model`" -ngl 999 -p `"The quick brown fox jumps over the lazy dog`" --pooling mean --embd-normalize 2" "embed_gpu"
    Invoke-Timed "llama-embedding.exe" "-m `"$model`" -ngl 999 -c 512 -b 512 -p `"$("word " * 120)`" --pooling mean --embd-normalize 2" "embed_gpu_long"
} else {
    # default: what the app does (flash attention AUTO resolves to on), then flash attention off, then q8_0 KV
    $doFa1 = $Only -in "all", "fa1"
    if ($doFa1) { Invoke-Timed "llama-bench.exe" "-m `"$model`" -ngl 999 -dev D3D12F0 -p $Pp -n $N -r 1 -fa 1" "bench_fa1" }
    if (-not $Fast) {
        if ($Only -in "all", "fa0")  { Invoke-Timed "llama-bench.exe" "-m `"$model`" -ngl 999 -dev D3D12F0 -p $Pp -n $N -r 1 -fa 0" "bench_fa0" }
        if ($Only -in "all", "kvq8") { Invoke-Timed "llama-bench.exe" "-m `"$model`" -ngl 999 -dev D3D12F0 -p 16 -n 4 -r 1 -fa 1 -ctk q8_0 -ctv q8_0" "bench_kvq8" }
    }
    if ($Check -and $doFa1) {
        $prompt = "The capital of France is Paris. The capital of Germany is"
        $common = "-m `"$model`" -p `"$prompt`" -n $CheckTokens -c 512 --temp 0 --seed 1 -no-cnv --no-warmup"
        Invoke-Timed "llama-completion.exe" "$common -ngl 0" "gen_cpu"
        Invoke-Timed "llama-completion.exe" "$common -ngl 999 -dev D3D12F0" "gen_gpu"
        $c = (Get-Content "$logs/gen_cpu.out.txt" -Raw); $g = (Get-Content "$logs/gen_gpu.out.txt" -Raw)
        $verdict = if ($c -and $g -and $c.Trim() -eq $g.Trim()) { "MATCH" } else { "DIFF" }
        "CPU vs GPU greedy generation: $verdict`n--- CPU ---`n$c`n--- GPU ---`n$g" | Out-File "$logs/check.txt"
    }
    if ($Ppl -and $doFa1) {
        # Perplexity of the same text on CPU and GPU: a numeric comparison of the logits, unlike greedy text
        # (near-ties in a small model flip a token without anything being wrong).
        $text = Join-Path $ws "README.md"
        $pcommon = "-m `"$model`" -f `"$text`" -c $PplCtx --chunks $PplChunks"
        Invoke-Timed "llama-perplexity.exe" "$pcommon -ngl 0" "ppl_cpu"
        Invoke-Timed "llama-perplexity.exe" "$pcommon -ngl 999 -dev D3D12F0" "ppl_gpu"
        function Get-Ppl($f) { $m = Select-String -Path $f -Pattern "Final estimate: PPL = ([0-9.]+)" | Select-Object -Last 1; if ($m) { [double]$m.Matches[0].Groups[1].Value } else { $null } }
        $pc = Get-Ppl "$logs/ppl_cpu.out.txt"; if (-not $pc) { $pc = Get-Ppl "$logs/ppl_cpu.err.txt" }
        $pg = Get-Ppl "$logs/ppl_gpu.out.txt"; if (-not $pg) { $pg = Get-Ppl "$logs/ppl_gpu.err.txt" }
        if ($pc -and $pg) {
            $rel = [math]::Abs($pg - $pc) / $pc
            $v = if ($rel -lt 0.01) { "OK" } else { "MISMATCH" }
            "PPL cpu=$pc gpu=$pg rel_diff=$([math]::Round($rel*100,4))% -> $v" | Tee-Object -Append "$logs/summary.txt" | Out-File "$logs/ppl.txt"
        } else { "PPL not parsed (cpu=$pc gpu=$pg)" | Tee-Object -Append "$logs/summary.txt" | Out-File "$logs/ppl.txt" }
    }
}

# verify: the cache-only build must never have needed a shader that is not in the cache
if ($Mode -eq "verify") {
    $miss = Select-String -Path "$logs/*.txt" -Pattern "precompiled shader missing for \[([^\]]*)\]" -ErrorAction SilentlyContinue |
            ForEach-Object { $_.Matches[0].Groups[1].Value } | Sort-Object -Unique
    if ($miss) { $miss | Out-File "$logs/MISSING.txt"; "MISSING SHADERS: $($miss.Count)" | Tee-Object -Append "$logs/summary.txt"; $script:failed = $true }
    else { "verify: no missing shaders" | Tee-Object -Append "$logs/summary.txt" }
    Remove-Item $model -ErrorAction SilentlyContinue
    if ($script:failed) { "VERIFY FAILED" | Tee-Object -Append "$logs/summary.txt"; exit 1 }
    exit 0
}

# coverage
$files = Get-ChildItem $cache -Filter *.dxil -ErrorAction SilentlyContinue
$man = if (Test-Path $env:GGML_D3D12_MANIFEST) { (Get-Content $env:GGML_D3D12_MANIFEST | Sort-Object -Unique).Count } else { 0 }
"baked: files=$($files.Count) bytes=$(($files | Measure-Object Length -Sum).Sum) manifest_unique=$man" | Tee-Object -Append "$logs/summary.txt"
if (Test-Path $env:GGML_D3D12_MANIFEST) { Copy-Item $env:GGML_D3D12_MANIFEST "$logs/manifest.txt" }
Remove-Item $model -ErrorAction SilentlyContinue
exit 0
