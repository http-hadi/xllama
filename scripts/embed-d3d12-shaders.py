#!/usr/bin/env python3
"""Embed the vendored HLSL as C++ string data that MSVC accepts.

The vendored hlsl/embed_hlsl.py emits one raw string literal per shader, up to ~180 KB; MSVC rejects any
literal over ~16 KB (C2026). This emits each shader as <=12 KB raw-literal chunks cut at line boundaries and
joins them once at startup, so the runtime string is byte-for-byte what embed_hlsl.py would have produced
(the shader cache key hashes it, so the two must agree).

    python scripts/embed-d3d12-shaders.py   # rewrites shaders/generated/ggml-d3d12-shaders.hpp
"""
import importlib.util
import os
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
hlsl_dir = root / "third_party" / "ggml-d3d12-full" / "hlsl"
out_path = root / "shaders" / "generated" / "ggml-d3d12-shaders.hpp"
CHUNK = 12000

spec = importlib.util.spec_from_file_location("embed_hlsl", hlsl_dir / "embed_hlsl.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

out = [
    "// Auto-generated by scripts/embed-d3d12-shaders.py - do not edit.\n",
    "// Chunked so no literal exceeds MSVC's limit (C2026); joined once at startup.\n",
    "#include <initializer_list>\n#include <string>\n\n",
    "static const char * ggml_d3d12_join(std::initializer_list<const char *> parts) {\n",
    "    std::string * s = new std::string();   // lives as long as the process, on purpose\n",
    "    for (const char * p : parts) {\n        s->append(p);\n    }\n    return s->c_str();\n}\n\n",
]
names = []
for fname in sorted(os.listdir(hlsl_dir)):
    if not fname.endswith(".hlsl"):
        continue
    name = fname[: -len(".hlsl")]
    names.append(name)
    code = mod.expand_includes((hlsl_dir / fname).read_text(encoding="utf-8"), str(hlsl_dir))
    delim = mod.raw_delim(code)
    chunks, cur, cur_bytes = [], [], 0
    for line in code.splitlines(keepends=True):
        n = len(line.encode("utf-8"))
        if n > CHUNK:
            sys.exit(f"{fname}: a single line is {n} bytes, cannot chunk")
        if cur_bytes + n > CHUNK and cur:
            chunks.append("".join(cur))
            cur, cur_bytes = [], 0
        cur.append(line)
        cur_bytes += n
    if cur:
        chunks.append("".join(cur))
    assert "".join(chunks) == code
    out.append(f"static const char * hlsl_{name} = ggml_d3d12_join({{\n")
    out.append(",\n".join(f'R"{delim}({c}){delim}"' for c in chunks))
    out.append("\n});\n\n")

out_path.write_text("".join(out), encoding="utf-8")
print(f"wrote {out_path} ({out_path.stat().st_size} bytes, {len(names)} shaders)")
